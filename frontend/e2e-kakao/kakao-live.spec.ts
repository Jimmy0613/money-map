import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";

test("실제 Kakao: 지도·검색·주소 변환·위치 저장·Marker 상세", async ({page}) => {
  const email=`kakao-test-${randomUUID()}@example.invalid`;
  const password=randomUUID()+"A1";
  const calls={sdk:0,search:0,address:0,region:0};
  page.on("response",response=>{
    const u=new URL(response.url());
    if(u.hostname!=="dapi.kakao.com" || !response.ok())return;
    if(u.pathname.endsWith("/maps/sdk.js"))calls.sdk++;
    if(u.pathname.includes("/search/keyword"))calls.search++;
    if(u.pathname.includes("/geo/coord2address"))calls.address++;
    if(u.pathname.includes("/geo/coord2regioncode"))calls.region++;
  });
  await page.goto("/signup");
  await page.getByLabel("이메일",{exact:true}).fill(email);
  await page.getByLabel("비밀번호",{exact:true}).fill(password);
  await page.getByLabel("비밀번호 확인",{exact:true}).fill(password);
  await page.getByRole("checkbox").check();
  await page.getByRole("button",{name:"회원가입",exact:true}).click();
  await expect(page.getByText("가입되었습니다. 로그인해 첫 거래를 기록하세요.")).toBeVisible();
  await page.getByRole("link",{name:"로그인",exact:true}).click();
  await page.getByLabel("이메일",{exact:true}).fill(email);
  await page.getByLabel("비밀번호",{exact:true}).fill(password);
  await page.getByRole("button",{name:"로그인",exact:true}).click();
  await page.getByRole("link",{name:"＋ 거래 기록"}).click();
  await page.getByLabel("금액 · 원").fill("1000");
  await page.getByLabel("카테고리",{exact:true}).selectOption({label:"식비"});
  await page.getByRole("button",{name:"지도 선택",exact:true}).click();
  await expect.poll(()=>page.locator('[aria-label="위치 선택 지도"] img').count(),{timeout:25000}).toBeGreaterThan(0);
  await page.getByRole("button",{name:"지도 중심 선택",exact:true}).click();
  await expect.poll(()=>calls.address>0&&calls.region>0).toBe(true);
  await expect(page.getByText("저장할 위치 미리보기")).toBeVisible();
  await page.getByRole("button",{name:"닫기",exact:true}).click();
  const previousAddress=calls.address,previousRegion=calls.region;
  await page.getByRole("button",{name:"장소 검색",exact:true}).click();
  await page.getByRole("textbox",{name:"장소 검색어"}).fill("서울시청");
  const first=page.getByRole("dialog").locator("ul.list li button").first();
  await expect(first).toBeVisible({timeout:25000});
  await first.click();
  await expect.poll(()=>calls.address>previousAddress&&calls.region>previousRegion).toBe(true);
  await page.getByRole("button",{name:"이 위치 확정",exact:true}).click();
  const created=page.waitForResponse(r=>new URL(r.url()).pathname==="/api/v1/transactions"&&r.request().method()==="POST");
  await page.getByRole("button",{name:"저장",exact:true}).click();
  const response=await created;
  expect(response.status()).toBe(201);
  const transaction=(await response.json()).data;
  expect(transaction.location?.source==="SEARCH").toBe(true);
  expect(/^\d{5}$/.test(transaction.location?.regionCode||"")).toBe(true);
  expect(Boolean(transaction.location?.roadAddress||transaction.location?.parcelAddress)).toBe(true);
  await expect(page.getByRole("heading",{name:"거래 상세"})).toBeVisible();
  await page.getByRole("link",{name:"지도",exact:true}).click();
  await expect.poll(()=>page.locator('[aria-label="소비 지도"] img').count(),{timeout:25000}).toBeGreaterThan(0);
  const marker=page.getByTitle(`${transaction.location.placeName} · 1000원 · 1건`,{exact:true});
  await expect(marker).toBeAttached();
  const markerImage=page.locator('[aria-label="소비 지도"] img[usemap]').first();
  await expect(markerImage).toBeVisible();
  await markerImage.click({position:{x:14,y:16}});
  await expect(page.getByRole("dialog")).toBeVisible();
  await expect(page.getByRole("dialog").getByText("1,000원",{exact:true}).first()).toBeVisible();
  await page.getByRole("button",{name:"닫기",exact:true}).click();
  await page.getByRole("button",{name:"확대",exact:true}).click();
  expect(calls.sdk).toBe(1);
  expect(calls.search>0&&calls.address>0&&calls.region>0).toBe(true);
  await page.getByRole("link",{name:"설정",exact:true}).click();
  await page.getByLabel("현재 비밀번호",{exact:true}).fill(password);
  await page.getByLabel("삭제 확인 · DELETE 입력",{exact:true}).fill("DELETE");
  await page.getByRole("button",{name:"계정과 데이터 삭제",exact:true}).click();
  await expect(page.getByRole("heading",{name:"다시 만나 반가워요"})).toBeVisible();
});
